#!/usr/bin/env node
/**
 * Forum P2P — CLI installer
 *   node scripts/install.mjs
 *   node scripts/install.mjs --yes --port=3000
 *   npm run install-node
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, writeFileSync, chmodSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { randomBytes } from "node:crypto";
import { createInterface } from "node:readline";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const args = process.argv.slice(2);
const autoYes = args.includes("--yes") || args.includes("-y");
const portArg = args.find((a) => a.startsWith("--port="));
const defaultPort = portArg ? portArg.split("=")[1] : "3000";

function log(msg) {
  console.log(`\x1b[36m[forum-p2p]\x1b[0m ${msg}`);
}
function fail(msg) {
  console.error(`\x1b[31m[forum-p2p]\x1b[0m ${msg}`);
  process.exit(1);
}
function ask(q, def = "") {
  if (autoYes) return Promise.resolve(def);
  const rl = createInterface({ input: process.stdin, output: process.stdout });
  return new Promise((resolveAsk) => {
    rl.question(`${q}${def ? ` [${def}]` : ""}: `, (ans) => {
      rl.close();
      resolveAsk(ans.trim() || def);
    });
  });
}

async function main() {
  console.log("");
  log("Forum P2P node installer");
  log(`Root: ${ROOT}`);
  log(`Node: ${process.version}`);

  const major = Number(process.versions.node.split(".")[0]);
  if (major < 18) fail("Need Node.js >= 18");

  if (!existsSync(join(ROOT, "package.json"))) fail("package.json missing — wrong folder?");

  log("npm install …");
  const npm = spawnSync("npm", ["install", "--omit=dev"], {
    cwd: ROOT,
    stdio: "inherit",
    shell: process.platform === "win32",
  });
  if (npm.status !== 0) fail("npm install failed");

  const port = await ask("PORT", defaultPort);
  const diskPath = await ask("DISK_PATH", "./data/network-data.disk");
  const signaling = await ask("SIGNALING_URL", "http://127.0.0.1:4000");
  let integrity = process.env.NODE_INTEGRITY_SECRET || "";
  if (!integrity) {
    integrity = randomBytes(32).toString("hex");
    log("Generated NODE_INTEGRITY_SECRET");
  }

  mkdirSync(join(ROOT, "data"), { recursive: true });
  const envPath = join(ROOT, ".env.local");
  writeFileSync(
    envPath,
    [
      `# Generated by scripts/install.mjs — ${new Date().toISOString()}`,
      `PORT=${port}`,
      `SIGNALING_URL=${signaling}`,
      `DISK_PATH=${diskPath}`,
      `MIN_DISK_GB=100`,
      `NODE_INTEGRITY_SECRET=${integrity}`,
      "",
    ].join("\n"),
    { mode: 0o600 }
  );
  try { chmodSync(envPath, 0o600); } catch {}

  writeFileSync(
    join(ROOT, "run-node.sh"),
    `#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")"
set -a
[ -f .env.local ] && . ./.env.local
set +a
echo "Forum P2P http://0.0.0.0:\${PORT:-3000}"
exec node src/index.js
`,
    { mode: 0o755 }
  );
  try { chmodSync(join(ROOT, "run-node.sh"), 0o755); } catch {}

  writeFileSync(
    join(ROOT, "run-node.ps1"),
    `Set-Location $PSScriptRoot
if (Test-Path .env.local) {
  Get-Content .env.local | ForEach-Object {
    if ($_ -match '^\\s*#' -or $_ -notmatch '=') { return }
    $k,$v = $_.Split('=',2)
    [Environment]::SetEnvironmentVariable($k.Trim(), $v.Trim(), 'Process')
  }
}
node src/index.js
`
  );

  mkdirSync(join(ROOT, "deploy"), { recursive: true });
  writeFileSync(
    join(ROOT, "deploy", "forum-p2p.service"),
    `[Unit]
Description=Forum P2P node
After=network.target
[Service]
Type=simple
WorkingDirectory=${ROOT}
EnvironmentFile=${envPath}
ExecStart=${process.execPath} ${join(ROOT, "src/index.js")}
Restart=on-failure
RestartSec=5
[Install]
WantedBy=multi-user.target
`
  );

  writeFileSync(
    join(ROOT, "data", ".install-stamp"),
    JSON.stringify({ version: "0.5.0", installedAt: new Date().toISOString(), node: process.version, port }, null, 2)
  );

  console.log(`
\x1b[32mInstall OK\x1b[0m

  ./run-node.sh          # Linux/macOS
  .\\run-node.ps1         # Windows
  npm run signaling      # other terminal for WebRTC

  Browser: http://127.0.0.1:${port}
  Docs: VERSION.md · CAI-DAT.md

  Note: Not a PHP app. Shared PHP-only hosting cannot run this node.
`);
}

main().catch((e) => fail(e.message || String(e)));
